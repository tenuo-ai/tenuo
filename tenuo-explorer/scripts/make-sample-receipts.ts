// Generates the Verify tab's sample receipts with the real TS SDK, so the
// samples are receipts Tenuo actually signs, not hand-made lookalikes.
//
//   node --experimental-strip-types scripts/make-sample-receipts.ts
//
// Writes src/sampleReceipts.ts: an allow, a deny, and a copy of the deny with
// one payload byte changed, which must fail signature verification.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createTenuo, pattern } from "../../tenuo-ts/packages/core/src/index.ts";

const T = createTenuo;
const control = createTenuo({ root: T.issuerKeyFromBytes(T.generateIssuerKey()) });
const root = control.issuerPublicKey();
const agentKey = T.generateHolderKey();
const issued = control.session({
  allow: { read_file: { path: pattern("docs/*") } },
  holder: T.publicKeyFromHolderKey(agentKey),
  ttlSeconds: 3600,
});
const agent = createTenuo({ trustedRoots: [root] });
const session = agent.sessionFromWire({ warrant: issued.toWire(), holderKey: agentKey });

const receipts: string[] = [];
const call = (path: string, requestId: string) => {
  try {
    agent.present(session, "read_file", { path }, { requestId, onReceipt: (r: string) => receipts.push(r) });
  } catch {
    // The denial is the point; its receipt was captured above.
  }
};
call("docs/readme.md", "sample-allow");
call("secrets/.env", "sample-deny");
if (receipts.length !== 2) throw new Error(`expected 2 receipts, got ${receipts.length}`);

// Flip one byte inside the deny's signed payload: it still parses, the signature fails.
const deny = receipts[1]!;
const at = Math.floor(deny.length / 4) * 2;
const flipped = (parseInt(deny.slice(at, at + 2), 16) ^ 0x01).toString(16).padStart(2, "0");
const tampered = deny.slice(0, at) + flipped + deny.slice(at + 2);

const [allowInfo, denyInfo] = receipts.map((r) => T.verifyReceipt(r));
if (allowInfo?.outcome !== "allow" || denyInfo?.outcome !== "deny") throw new Error("unexpected outcomes");
let failed = false;
try { T.verifyReceipt(tampered); } catch (e) { failed = /signature does not verify/.test((e as Error).message); }
if (!failed) throw new Error("tampered receipt did not fail signature verification");

const out = fileURLToPath(new URL("../src/sampleReceipts.ts", import.meta.url));
const trustedRoot = (root as unknown as { hex: string }).hex;
const data = JSON.stringify({ trustedRoot, receipts: [...receipts, tampered] }, null, 2);
writeFileSync(out, `// Generated by scripts/make-sample-receipts.ts. Do not edit by hand.
// Line 1 allows, line 2 denies, line 3 is line 2 with one byte changed.
export const SAMPLE_RECEIPTS: { trustedRoot: string; receipts: string[] } = ${data};
`);
console.log(`wrote ${out}`);
